def test_envfile_quotes_values_that_need_it(tmp_path: Path) -> None:
    env = EnvFile(["A=1  # note", "B="])
    env.set("B", "has space # and hash")
    env.set("C", "plain")
    env.set("A", "2")
    path = tmp_path / "x.env"
    env.write(path)
    reloaded = EnvFile.load(path, EXAMPLE)
