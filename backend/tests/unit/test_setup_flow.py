    assert env.get("LLM_FAST_MODEL") == "gemini-2.5-flash"
    assert env.get("GOOGLE_API_KEY") == GOOGLE_KEY
    assert sum("Google" in prompt or "Gemini" in prompt for prompt, s in p.prompts if s) == 1


